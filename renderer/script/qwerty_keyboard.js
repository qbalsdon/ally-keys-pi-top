function generateAria(text) {
    if (text == "") return "";

    return `aria-label="${text}"`;
}

function createKey(data) {
    const keyTemplate = `<div class="__CLASS__" role="button" data-value="__KEY_DATA__" tabindex="1001" __ARIA__>__CONTENT__</div>`;

    return keyTemplate
        .replace("__CLASS__", `key ${data["class"]}`)
        .replace("__KEY_DATA__", data["data"])
        .replace("__CONTENT__", data["content"])
        .replace("__ARIA__", generateAria(data["aria-label"]));
}

function createKeyboard(container, keyLayout) {
    const keyTemplate = `<div class="__CLASS__" role="button" data-value="__KEY_DATA__" tabindex="1001" __ARIA__>__CONTENT__</div>`;

    let functionKeys = "";
    let rows = "";
    let bottomRow = "";
    let arrows = "";

    for (let i = 0; i < keyLayout.function_keys.length; i++) {
        functionKeys += createKey(keyLayout.function_keys[i]);
    }

    for (let i = 0; i < keyLayout.rows.length; i++) {
        const rowKeys = keyLayout.rows[i];
        rows += "<div class='keyboard-row'>";
        for (let j = 0; j < rowKeys.content.length; j++) {
            rows += createKey(rowKeys.content[j]);
        }
        rows += "</div>";
    }

    for (let i = 0; i < keyLayout.bottomRow.length; i++) {
        bottomRow += createKey(keyLayout.bottomRow[i]);
    }

    arrows += createKey(keyLayout.arrows[0]);
    arrows += "<div class='up-down'>";
    arrows += createKey(keyLayout.arrows[1]);
    arrows += createKey(keyLayout.arrows[2]);
    arrows += "</div>";
    arrows += createKey(keyLayout.arrows[3]);

    const keyBoard = document.getElementById(container);
    keyBoard.innerHTML = `
    <div class="keyboard-decor apple-keyboard">
        <div class="header">
            <h1 class="keyboard">
                <span class="header-line">
                    CSS Flexbox Apple Keyboard by <a href="https://olex.co/"><u>Olex Ponomarenko</u></a>
                    Modified by <a href="https://qbalsdon.github.io/about/"><u>Quintin</u></a>
                </span>
                <span>
                    <input type="checkbox" id="combo" tabindex="1000"><label for="combo"> Combo</label>
                </span>
            </h1>
        </div>
        <div class="keyboard" id="base-keyboard">
            <div class="keyboard-row thin">
                ${functionKeys}
            </div>
            ${rows}
            <div class="keyboard-row bottom-row">
                ${bottomRow}
                <div class="arrows">
                    ${arrows}
                </div>
            </div>        
        </div>
    </div>    
    `;
}

